#!/usr/bin/env python3
"""Generate NOTICE from the Rust dependency graph.

Domowik ships under Apache-2.0, and docs/THIRD-PARTY-POLICY.md requires every
DISTRIBUTED dependency to be recorded with its notices. Several of the crates
in the runtime graph carry licences that REQUIRE reproduction — BSD-2-Clause
and BSD-3-Clause both say the copyright notice and disclaimer must appear in
distributions, and Apache-2.0 §4(d) requires carrying forward any NOTICE file.

This reproduces them from the crates' own sources rather than from a
hand-maintained list, because a hand-maintained list is exactly what goes stale
the first time a dependency changes.

Scope, stated because the file itself is an assertion:

- RUNTIME crates only. Dev-dependencies are not distributed and their notices
  are not obligations; `docs/RUST-DEPENDENCIES.md` still records them.
- BUNDLED NON-CODE ASSETS too, read from `docs/third-party/assets.json`. A
  font embedded in the binary is distributed exactly as a crate is, and its
  licence obligations are the same, but `cargo metadata` cannot see it — so
  without this the one component with an attribution requirement nobody can
  satisfy by reading Cargo.toml would be the one left out.
- Licence TEXTS are copied verbatim from each crate's own LICENSE, LICENCE,
  COPYING or NOTICE files. A crate shipping none is listed with its declared
  SPDX expression and flagged, because "we could not find the text" is a fact
  a reader needs, not one to paper over.
- This is a mechanical record, NOT a licence audit and NOT legal advice. It
  reports what the crates declare and ship.

`scripts/verify.sh` regenerates this and diffs it, so a dependency change fails
the build until the notice is refreshed.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys

LICENCE_PREFIXES = ("LICENSE", "LICENCE", "COPYING", "NOTICE")
# Bundled non-code assets, recorded by hand because no build tool knows about
# them. The path is relative to the repository root.
ASSETS_RECORD = "docs/third-party/assets.json"
# Longer texts are summarised by name: the point is attribution and the
# obligation to reproduce, and a NOTICE that nobody opens because it is
# megabytes long serves neither.
MAX_TEXT_BYTES = 40_000


def licence_files(directory: str) -> list[str]:
    if not os.path.isdir(directory):
        return []
    names = [
        n
        for n in sorted(os.listdir(directory))
        if n.upper().startswith(LICENCE_PREFIXES)
        and os.path.isfile(os.path.join(directory, n))
    ]
    return names


def bundled_assets(root: str) -> list[dict]:
    """The distributed non-code assets, or none when the record is absent."""
    path = os.path.join(root, ASSETS_RECORD)
    if not os.path.isfile(path):
        return []
    with open(path, encoding="utf-8") as handle:
        record = json.load(handle)
    return [a for a in record.get("assets", []) if a.get("status") == "distributed"]


def main() -> int:
    meta = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--format-version", "1", "--locked"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout
    )
    by_id = {p["id"]: p for p in meta["packages"]}
    workspace = set(meta["workspace_members"])

    # The runtime graph: everything reachable through normal dependencies from
    # a workspace member, excluding dev-only edges.
    resolve = {n["id"]: n for n in meta["resolve"]["nodes"]}
    runtime: set[str] = set()
    stack = list(workspace)
    while stack:
        current = stack.pop()
        for dep in resolve.get(current, {}).get("deps", []):
            if all(k.get("kind") == "dev" for k in dep.get("dep_kinds", [])):
                continue
            if dep["pkg"] in runtime:
                continue
            runtime.add(dep["pkg"])
            stack.append(dep["pkg"])

    third_party = sorted(
        (by_id[i] for i in runtime if i not in workspace),
        key=lambda p: (p["name"], p["version"]),
    )

    out: list[str] = []
    out.append("Domowik")
    out.append("Copyright the Domowik contributors")
    out.append("")
    out.append("This product is licensed under the Apache License, Version 2.0.")
    out.append("")
    out.append(
        "GENERATED by scripts/rust-notice.py. Do not edit by hand;"
    )
    out.append(
        "`scripts/verify.sh` regenerates this file and fails on any difference."
    )
    out.append("")
    out.append(
        "This file records the third-party components DISTRIBUTED with Domowik"
    )
    out.append(
        "and reproduces their notices, as docs/THIRD-PARTY-POLICY.md requires."
    )
    out.append(
        "Development-only tooling is not distributed and is not listed here;"
    )
    out.append("docs/RUST-DEPENDENCIES.md records it.")
    out.append("")
    out.append(
        "It is a mechanical record, NOT a licence audit and NOT legal advice."
    )
    out.append("")
    root = meta["workspace_root"]
    assets = bundled_assets(root)
    out.append(
        f"{len(third_party)} distributed third-party crates"
        f" and {len(assets)} bundled asset(s)."
    )
    out.append("")

    missing: list[str] = []
    for pkg in third_party:
        directory = os.path.dirname(pkg["manifest_path"])
        names = licence_files(directory)
        out.append("=" * 72)
        out.append(f"{pkg['name']} {pkg['version']}")
        out.append(f"Declared licence: {pkg.get('license') or 'not declared'}")
        if pkg.get("repository"):
            out.append(f"Source: {pkg['repository']}")
        out.append("")
        if not names:
            missing.append(f"{pkg['name']} {pkg['version']}")
            out.append(
                "  No LICENSE, COPYING or NOTICE file ships with this crate's"
            )
            out.append(
                "  source. Only the declared SPDX expression above is recorded."
            )
            out.append("")
            continue
        for name in names:
            path = os.path.join(directory, name)
            size = os.path.getsize(path)
            out.append(f"--- {name} ---")
            if size > MAX_TEXT_BYTES:
                out.append(
                    f"  ({size} bytes; the full text ships with the crate source)"
                )
                out.append("")
                continue
            with open(path, encoding="utf-8", errors="replace") as handle:
                out.append(handle.read().rstrip())
            out.append("")

    for asset in assets:
        out.append("=" * 72)
        out.append(f"{asset['name']} {asset['version']}")
        out.append(f"Declared licence: {asset.get('license') or 'not declared'}")
        if asset.get("sourceUrl"):
            source = asset["sourceUrl"]
            if asset.get("commitSha"):
                source += f" @ {asset['commitSha']}"
            out.append(f"Source: {source}")
        if asset.get("path"):
            out.append(f"Bundled at: {asset['path']}")
        if asset.get("sha256"):
            out.append(f"SHA-256: {asset['sha256']}")
        out.append(
            "Modified: " + ("yes" if asset.get("modified") else "no")
        )
        out.append("")
        text_path = asset.get("licenseTextPath")
        if not text_path or not os.path.isfile(os.path.join(root, text_path)):
            missing.append(f"{asset['name']} {asset['version']}")
            out.append(
                "  No licence text is committed beside this asset. Only the"
            )
            out.append("  declared licence above is recorded.")
            out.append("")
            continue
        out.append(f"--- {os.path.basename(text_path)} ---")
        with open(os.path.join(root, text_path), encoding="utf-8", errors="replace") as handle:
            out.append(handle.read().rstrip())
        out.append("")

    if missing:
        out.append("=" * 72)
        out.append("Components shipping no licence text in their source:")
        for name in missing:
            out.append(f"  - {name}")
        out.append("")

    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
